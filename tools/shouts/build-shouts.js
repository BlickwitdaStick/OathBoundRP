#!/usr/bin/env node
'use strict';
/**
 * Builds skymp/gamemode/data/shouts.json: the shouts a player can learn, from
 * the game's SHOU records (Skyrim.esm, Dawnguard.esm, Dragonborn.esm). A
 * player shout has three real, distinct words of power (WOOP); dragon,
 * Greybeard and quest copies reuse placeholder words and are left out.
 *
 *   node tools/shouts/build-shouts.js [Skyrim Data folder]
 *
 * Names are not in the masters (they are localized); NAMES gives the in-game
 * name per editor id, and anything new falls back to a name made from the id.
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const DATA = process.argv[2] || 'E:\\SkyrimRP\\Skyrim Special Edition\\Data';
const OUT = path.join(__dirname, '..', '..', 'skymp', 'gamemode', 'data', 'shouts.json');
const MASTERS = ['Skyrim.esm', 'Dawnguard.esm', 'Dragonborn.esm'];
const PLACEHOLDER_WORDS = new Set([0x252c3, 0x252c4, 0x252c5, 0xff8d7]);
const SKIP = /^(L_|L?Shout|Dragon|DLC\dDragon|Greybeard|MQ|dun|DA\d|cr|Howl|Alduin|UnrelentingForceShoutDraugr)/;
// No dragons in OATHBOUND: shouts that call, summon or fight dragons are left out too.
const NO_DRAGONS = new Set(['CallDragonShout', 'DLC1SummonDragonShout', 'DragonrendShout']);

const NAMES = {
  UnrelentingForceShout: 'Unrelenting Force', WhirlwindSprintShout: 'Whirlwind Sprint', FireBreathShout: 'Fire Breath',
  FrostBreathShout: 'Frost Breath', IceFormShout: 'Ice Form', DisarmShout: 'Disarm', Dismay: 'Dismay',
  ThrowVoiceShout: 'Throw Voice', KynesPeaceShout: "Kyne's Peace", StormCallShout: 'Storm Call',
  MarkedforDeathShout: 'Marked for Death', AuraWhisperShout: 'Aura Whisper', animalAllegianceShout: 'Animal Allegiance',
  BecomeEtherealShout: 'Become Ethereal', ClearSkiesShout: 'Clear Skies', ElementalFuryShout: 'Elemental Fury',
  SlowTimeShout: 'Slow Time', CallofValorShout: 'Call of Valor', CallOfValorShout: 'Call of Valor',
  DLC1SoulTearShout: 'Soul Tear', DLC1SummonDurnehviirShout: 'Summon Durnehviir', DLC1DrainVitalityShout: 'Drain Vitality',
  DLC2BendWillShout: 'Bend Will', DLC2DragonAspectShout: 'Dragon Aspect', DLC2CycloneShout: 'Cyclone',
  DLC2BattleFuryShout: 'Battle Fury', DLC2WhirlwindSprintShout: 'Whirlwind Sprint'
};

function nameOf(editorId) {
  if (NAMES[editorId]) return NAMES[editorId];
  return editorId.replace(/^DLC\d/, '').replace(/Shout$/, '').replace(/([a-z])([A-Z])/g, '$1 $2').trim();
}

function fields(d) {
  const out = [];
  let p = 0;
  while (p + 6 <= d.length) {
    const type = d.toString('latin1', p, p + 4);
    const size = d.readUInt16LE(p + 4);
    out.push({ type, data: d.slice(p + 6, p + 6 + size) });
    p += 6 + size;
  }
  return out;
}

function readShouts(file) {
  const b = fs.readFileSync(path.join(DATA, file));
  const shouts = [];
  (function walk(start, end) {
    let o = start;
    while (o < end) {
      const type = b.toString('latin1', o, o + 4);
      const size = b.readUInt32LE(o + 4);
      if (type === 'GRUP') { walk(o + 24, o + size); o += size; continue; }
      if (type === 'SHOU') {
        const flags = b.readUInt32LE(o + 8);
        let d = b.slice(o + 24, o + 24 + size);
        if (flags & 0x40000) d = zlib.inflateSync(d.slice(4));
        const f = fields(d);
        const edid = (f.find((x) => x.type === 'EDID') || { data: Buffer.alloc(0) }).data.toString('latin1').replace(/\0/g, '');
        const words = f.filter((x) => x.type === 'SNAM').map((x) => x.data.readUInt32LE(0));
        shouts.push({ formId: b.readUInt32LE(o + 12), editorId: edid, words });
      }
      o += 24 + size;
    }
  })(0, b.length);
  return shouts;
}

/** FormDesc for a record of a master: local id within its own plugin. */
function desc(formId, file) {
  const own = formId >>> 24;
  // Skyrim.esm records keep index 00; a DLC record's own index is its position among its masters.
  const plugin = own === 0 ? 'Skyrim.esm' : file;
  return `${(formId & 0x00ffffff).toString(16)}:${plugin}`;
}

const out = [];
for (const file of MASTERS) {
  for (const s of readShouts(file)) {
    const words = s.words.filter((w) => w && !PLACEHOLDER_WORDS.has(w & 0x00ffffff));
    const skipped = SKIP.test(s.editorId) && s.editorId !== 'DLC2DragonAspectShout';
    if (words.length !== 3 || new Set(words).size !== 3 || skipped || NO_DRAGONS.has(s.editorId)) continue;
    out.push({ key: nameOf(s.editorId).toLowerCase().replace(/'/g, '').replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, ''),
      name: nameOf(s.editorId), editorId: s.editorId, shout: desc(s.formId, file), words: words.map((w) => desc(w, file)) });
  }
}
out.sort((a, b) => a.name.localeCompare(b.name));
const keys = new Set();
for (const s of out) {
  while (keys.has(s.key)) s.key += '_2';
  keys.add(s.key);
}
fs.writeFileSync(OUT, JSON.stringify({ '//': 'Generated by tools/shouts/build-shouts.js. Shouts a player can learn; only the Council grants them.', shouts: out }, null, 1) + '\n');
console.log(`wrote ${OUT}: ${out.length} shouts`);
console.log(out.map((s) => `${s.key} (${s.editorId})`).join(', '));
